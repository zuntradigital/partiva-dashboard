type Dict = typeof dict;

function getPath(obj: unknown, path: string): unknown {
  return path.split(".").reduce<unknown>((acc, key) => (acc && typeof acc === "object" ? (acc as Record<string, unknown>)[key] : undefined), obj);
}

function interpolate(template: string, vars?: Record<string, string | number>): string {
  if (!vars) return template;
  return template.replace(/\{\{(\w+)\}\}/g, (_, key: string) => String(vars[key] ?? ""));
}

interface LanguageContextValue {
  lang: Lang;
  dir: "rtl" | "ltr";
  setLang: (lang: Lang) => void;
  toggleLang: () => void;
  t: (key: string, vars?: Record<string, string | number>) => string;
}

const LanguageContext = createContext<LanguageContextValue | null>(null);

function applyLang(lang: Lang) {
  document.documentElement.lang = lang;
  document.documentElement.dir = lang === "ar" ? "rtl" : "ltr";
  window.localStorage.setItem(STORAGE_KEY, lang);
}

export function LanguageProvider({ children }: { children: React.ReactNode }) {
  // Always starts "ar" to match the server-rendered markup exactly -- the
  // inline script in layout.tsx already applied the real language to the DOM
  // before hydration, so this effect just reads it back afterwards instead
  // of guessing during render (same pattern as useTheme in theme.ts).
  const [lang, setLangState] = useState<Lang>("ar");

  useEffect(() => {
    setLangState(document.documentElement.lang === "en" ? "en" : "ar");
  }, []);

  const setLang = useCallback((next: Lang) => {
    applyLang(next);
    setLangState(next);
  }, []);

  const toggleLang = useCallback(() => setLang(lang === "ar" ? "en" : "ar"), [lang, setLang]);

  const t = useCallback(
    (key: string, vars?: Record<string, string | number>) => {
      const entry = getPath(dict, key) as { ar: string; en: string } | undefined;
      if (!entry) return key;
      return interpolate(entry[lang], vars);
    },
    [lang],
  );

  return (
    <LanguageContext.Provider value={{ lang, dir: lang === "ar" ? "rtl" : "ltr", setLang, toggleLang, t }}>
      {children}
    </LanguageContext.Provider>
  );
}

export function useLanguage(): LanguageContextValue {
  const ctx = useContext(LanguageContext);
  if (!ctx) throw new Error("useLanguage must be used within LanguageProvider");
  return ctx;
}

